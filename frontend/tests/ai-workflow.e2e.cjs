/* Document workflow smoke test, disposable account and local rules only. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');

async function main() {
  const root = path.resolve(__dirname, '../..'), logs = path.join(root, 'logs');
  await fs.mkdir(logs, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN', acceptDownloads: true });
  const page = await context.newPage(), errors = [];
  page.setDefaultTimeout(30000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/\/recommend$/.test(request.url())) assert.equal(request.postDataJSON().allow_ai, false); });
  const username = 'qa_ai_' + Date.now();
  const response = await context.request.post('http://127.0.0.1:5000/api/auth/register', { data: { username, password: 'qa-test-only-password', role: 'user' } });
  assert.equal(response.status(), 200);
  const auth = (await response.json()).data;
  await fs.writeFile(path.join(logs, 'ai-ui-test-account.json'), JSON.stringify({ username, user_id: auth.user.id }));
  await context.addInitScript(token => { localStorage.setItem('ramancloud_auth_token', token); localStorage.setItem('ramancloud_language', 'zh'); }, auth.token);
  const flow = () => page.getByRole('navigation', { name: '分析流程', exact: true });
  async function go(name) { await flow().getByRole('button', { name: new RegExp(name) }).click(); }
  const headers = { Authorization: 'Bearer ' + auth.token };
  async function currentVersion() {
    const url = new URL(page.url());
    return (await context.request.get(`http://127.0.0.1:5000/api/ai-workflows/${url.searchParams.get('task')}/versions/${url.searchParams.get('version')}`, { headers })).json();
  }
  async function screenshot(name) {
    await page.locator('.welcome-screen').waitFor({ state: 'hidden' });
    await page.screenshot({ path: path.join(logs, name + '.png'), animations: 'disabled' });
  }
  try {
    await page.goto('http://127.0.0.1:5173/preprocessing/ai-analysis');
    await page.getByRole('heading', { name: '智能光谱处理', exact: true }).waitFor();
    await page.getByRole('link', { name: '智能光谱处理', exact: true }).waitFor();
    await page.locator('.welcome-screen.is-hidden').waitFor({ state: 'attached' });
    await page.getByLabel('示例光谱', { exact: true }).selectOption('tutorial');
    await page.getByRole('heading', { name: '格式检查通过', exact: true }).waitFor();
    assert.equal(await page.getByLabel('分析目标', { exact: true }).count(), 0);
    assert.equal(await flow().getByRole('button', { name: /目标细调/ }).isDisabled(), true);
    await page.getByLabel('起始波数', { exact: true }).fill('400');
    await page.getByLabel('终止波数', { exact: true }).fill('401');
    assert.equal(await page.getByRole('button', { name: '生成预处理方案', exact: true }).isDisabled(), true);
    await page.getByLabel('终止波数', { exact: true }).fill('1800');
    await screenshot('document-upload-desktop');
    const recommended = page.waitForResponse(value => /\/recommend$/.test(value.url()));
    await page.getByRole('button', { name: '生成预处理方案', exact: true }).click();
    const proposal = (await (await recommended).json()).version;
    assert.equal(proposal.metadata.phase, 'preprocess');
    assert.equal(proposal.metadata.candidates.length, 3);
    assert.equal(proposal.analysis_run_id, null);
    await page.getByLabel('步骤 3 算法').waitFor();
    assert.deepEqual(proposal.steps.map(step => step.type), ['cut', 'despike', 'denoise', 'baseline']);
    assert.equal(await page.locator('.ai-step').count(), proposal.steps.length);
    assert.equal(await page.locator('.ai-step-title').textContent(), '去鬼峰');
    assert.match(await page.locator('.ai-plan').innerText(), /本地规则/);
    assert.equal(await page.locator('.ai-band-fields').count(), 0);
    assert.equal(await page.locator('.ai-step-details[open]').count(), 0);
    await page.getByRole('button', { name: '调整处理波段', exact: true }).click();
    assert.equal(await page.locator('.ai-band-fields').getByLabel('终止波数', { exact: true }).inputValue(), '1800');
    await page.getByRole('button', { name: '调整处理波段', exact: true }).click();
    await go('上传数据');
    await page.getByRole('button', { name: '继续当前分析', exact: true }).click();
    assert.equal((await currentVersion()).id, proposal.id);
    assert.equal(await page.getByLabel('方案版本', { exact: true }).locator('option').count(), 1);
    await page.locator('.ai-candidates summary').click();
    const alternatives = page.locator('.ai-candidates input[type="radio"]:not(:checked)');
    const candidateChange = page.waitForResponse(value => /\/candidates\/[^/]+$/.test(value.url()) && value.request().method() === 'POST');
    await alternatives.first().click();
    assert.equal((await candidateChange).status(), 200);
    await page.getByLabel('方案版本', { exact: true }).locator('option').filter({ hasText: 'V2' }).waitFor({ state: 'attached' });
    await screenshot('document-preprocessing-desktop');
    await page.getByRole('button', { name: '确认并自动预处理', exact: true }).click();
    await page.getByRole('link', { name: '已保存至分析历史', exact: true }).waitFor();
    assert.equal(await page.getByLabel('分析目标', { exact: true }).count(), 0);
    assert.equal(await flow().getByRole('button', { name: /结果展示/ }).getAttribute('aria-current'), 'step');
    assert.equal(await page.getByRole('button', { name: '确认更新并保存', exact: true }).count(), 0);
    await screenshot('streamlined-result-desktop');
    await page.getByRole('button', { name: '继续目标细调', exact: true }).click();
    await page.getByLabel('分析目标', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '更新方案并预览', exact: true }).isDisabled(), true);
    assert.equal(await flow().getByRole('button', { name: /目标细调/ }).isDisabled(), false);
    const originalVersion = await currentVersion();
    assert.equal(originalVersion.status, 'completed');
    const baselineIndex = originalVersion.steps.findIndex(step => step.type === 'baseline');
    const denoiseIndex = originalVersion.steps.findIndex(step => step.method === 'sg');
    const baselineParams = originalVersion.steps[baselineIndex].params;
    await page.getByLabel('分析目标', { exact: true }).fill('去除背景、适度降噪，保留主要峰');
    await page.getByLabel('调整反馈', { exact: true }).fill('峰变弱了，减小平滑窗口，其他步骤保持不变');
    await page.getByRole('button', { name: '查看当前结果', exact: true }).click();
    await page.getByRole('status').filter({ hasText: '调整需求尚未应用' }).waitFor();
    await go('保存与复现');
    assert.equal(await page.getByRole('button', { name: '新版本复现', exact: true }).isDisabled(), true);
    assert.equal(await page.getByRole('button', { name: '确认执行并保存', exact: true }).count(), 0);
    await page.getByRole('button', { name: '返回确认修改', exact: true }).click();
    assert.equal(await page.getByLabel('调整反馈', { exact: true }).inputValue(), '峰变弱了，减小平滑窗口，其他步骤保持不变');
    await page.getByRole('button', { name: '更新方案并预览', exact: true }).click();
    await page.getByRole('button', { name: '确认更新并保存', exact: true }).waitFor();
    const refined = await currentVersion();
    assert.equal(refined.status, 'preview');
    assert.equal(refined.metadata.phase, 'refine');
    assert.equal(refined.reused_steps, denoiseIndex);
    assert.deepEqual(refined.steps[baselineIndex].params, baselineParams);
    assert.equal(await page.locator('.ai-step-compute').filter({ hasText: '复用既有结果' }).count(), denoiseIndex);
    assert.equal(await page.getByRole('button', { name: '预览', exact: true }).count(), 0);
    await page.locator('.ai-step').nth(denoiseIndex).locator('summary').click();
    const sgWindow = page.locator('.ai-step').nth(denoiseIndex).locator('input[type="number"]').first();
    await sgWindow.fill('6');
    await page.getByRole('button', { name: '预览', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '奇数' }).waitFor();
    await sgWindow.fill('7');
    const editedPreview = page.waitForResponse(value => /\/preview$/.test(value.url()) && value.request().method() === 'POST');
    await page.getByRole('button', { name: '预览', exact: true }).click();
    assert.equal((await editedPreview).status(), 200);
    await page.locator('.ai-dirty').waitFor({ state: 'hidden' });
    const edited = await currentVersion();
    assert.equal(edited.reused_steps, denoiseIndex);
    assert.equal(edited.preview[denoiseIndex].reused, false);
    await page.getByLabel('查看处理步骤', { exact: true }).selectOption(`step:${baselineIndex}`);
    assert.equal(await page.locator('.ai-chart .scatterlayer .js-line').count(), 3);
    await page.getByRole('button', { name: '步骤残差', exact: true }).click();
    assert.equal(await page.getByLabel('查看处理步骤', { exact: true }).inputValue(), `step:${baselineIndex}`);
    assert.equal(await page.locator('.ai-chart .scatterlayer .js-line').count(), 1);
    await screenshot('document-review-desktop');
    await page.getByRole('button', { name: '确认更新并保存', exact: true }).click();
    await page.getByRole('link', { name: '已保存至分析历史', exact: true }).waitFor();
    const saved = await currentVersion();
    assert.equal(saved.status, 'completed');
    const oldResponse = await context.request.get(`http://127.0.0.1:5000/api/ai-workflows/${new URL(page.url()).searchParams.get('task')}/versions/${originalVersion.id}`, { headers });
    assert.deepEqual((await oldResponse.json()).trace, originalVersion.trace);
    await go('保存与复现');
    const downloaded = page.waitForEvent('download');
    await page.getByRole('button', { name: '过程包', exact: true }).click();
    await (await downloaded).saveAs(path.join(logs, 'document-workflow.zip'));
    const replayStarted = page.waitForResponse(value => /\/execute$/.test(value.url()) && value.request().method() === 'POST');
    await page.getByRole('button', { name: '新版本复现', exact: true }).click();
    assert.equal((await replayStarted).status(), 200);
    await page.locator('.ai-archive').getByText('已保存', { exact: true }).waitFor();
    const replay = await currentVersion();
    assert.notEqual(replay.id, saved.id);
    assert.equal(replay.reused_steps, 0);
    assert.deepEqual(replay.trace.at(-1).after, saved.trace.at(-1).after);
    await go('上传数据');
    await page.getByLabel('终止波数', { exact: true }).fill('401');
    await go('结果展示');
    assert.equal(await page.getByRole('button', { name: '预览', exact: true }).isDisabled(), true);
    await go('保存与复现');
    assert.equal(await page.getByRole('button', { name: '新版本复现', exact: true }).isDisabled(), true);
    await page.reload();
    await page.getByLabel('方案版本', { exact: true }).waitFor();
    await go('保存与复现');
    await screenshot('document-save-desktop');
    await page.setViewportSize({ width: 390, height: 844 });
    for (const [name, file] of [['上传数据', 'document-upload-mobile'], ['自动预处理', 'document-preprocessing-mobile'], ['目标细调', 'document-refine-mobile'], ['结果展示', 'document-review-mobile'], ['保存与复现', 'document-save-mobile']]) {
      await go(name);
      await screenshot(file);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
      const clipped = await page.locator('.ai-workspace button').evaluateAll(elements => elements.filter(el => el.clientWidth > 0 && el.scrollWidth > el.clientWidth + 3).map(el => el.textContent));
      assert.deepEqual(clipped, []);
    }
    await page.getByLabel('方案版本', { exact: true }).selectOption(originalVersion.id);
    await page.locator('.ai-results').waitFor();
    await go('自动预处理');
    await page.locator('.ai-candidates').waitFor();
    await page.locator('.ai-candidates summary').click();
    await page.locator('.ai-candidates').scrollIntoViewIfNeeded();
    await screenshot('document-candidates-mobile');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.getByLabel('方案版本', { exact: true }).selectOption(replay.id);
    await page.locator('.ai-results').waitFor();
    await page.locator('.ai-results').scrollIntoViewIfNeeded();
    assert.ok(await page.locator('.ai-chart .scatterlayer .js-line').count() >= 2);
    await screenshot('document-curves-mobile');
    await page.evaluate(() => localStorage.setItem('ramancloud_theme', 'dark'));
    await page.reload(); await page.getByLabel('方案版本', { exact: true }).waitFor();
    await page.locator('.ai-results').scrollIntoViewIfNeeded();
    await screenshot('document-review-dark-mobile');
    assert.deepEqual(errors, []);
    console.log('DOCUMENT_WORKFLOW_E2E_OK upload/range/candidates/confirm/refine/incremental-recompute/versions/replay/download/desktop/mobile/dark');
  } finally {
    await context.close(); await browser.close();
    const cleanup = spawnSync(process.env.BACKEND_PYTHON || process.env.PYTHON_PATH || 'python', ['backend/tests/cleanup_ui_test.py', 'ai-ui-test-account.json'], { cwd: root, encoding: 'utf8' });
    if (cleanup.status !== 0) throw new Error('QA cleanup failed: ' + cleanup.stderr);
    console.log(cleanup.stdout.trim());
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
