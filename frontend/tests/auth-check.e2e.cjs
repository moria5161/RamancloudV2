const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');

async function main() {
  const logs = path.resolve(__dirname, '../../logs');
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'zh-CN' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.addInitScript(() => localStorage.setItem('ramancloud_language', 'zh'));
  const report = { username: 'qa_ai_' + Date.now(), errors };
  await fs.mkdir(logs, { recursive: true });
  const register = await context.request.post('http://127.0.0.1:5000/api/auth/register', { data: { username: report.username, password: 'qa-test-only-password', role: 'user' } });
  assert.equal(register.status(), 200);
  const auth = (await register.json()).data;
  report.user_id = auth.user.id;
  await fs.writeFile(path.join(logs, 'auth-ui-test-account.json'), JSON.stringify(report));
  try {
    await page.goto('http://127.0.0.1:5173/preprocessing/');
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    if (process.env.AUTH_PROBE === '1') {
      report.logged_out_login_visible = true;
      await page.getByRole('button', { name: '注册', exact: true }).click();
      await page.getByLabel('用户名', { exact: true }).fill('a');
      await page.getByLabel('密码', { exact: true }).fill('qa-test-only-password');
      await page.getByRole('button', { name: '创建账号', exact: true }).click();
      await page.waitForTimeout(700);
      report.validation_caused_blank_page = await page.locator('form').count() === 0;
      report.validation_errors = [...errors];
      await page.screenshot({ path: path.join(logs, 'auth-before.png') });
      await page.goto('http://127.0.0.1:5173/preprocessing/');
      await page.evaluate(token => localStorage.setItem('ramancloud_auth_token', token), auth.token);
      await page.goto('http://127.0.0.1:5173/preprocessing/login');
      await page.getByRole('navigation').waitFor();
      report.saved_session_login_form_visible = await page.locator('form').count() > 0;
      console.log(JSON.stringify(report, null, 2));
      return;
    }

    assert.equal(new URL(page.url()).pathname, '/preprocessing/login');
    await page.screenshot({ path: path.join(logs, 'auth-login-desktop.png') });
    await page.getByRole('button', { name: '注册', exact: true }).click();
    assert.equal(new URL(page.url()).pathname, '/preprocessing/register');
    assert.equal(await page.getByLabel('账号类型').count(), 0);
    await page.getByLabel('用户名', { exact: true }).fill('a');
    await page.getByLabel('密码', { exact: true }).fill('qa-test-only-password');
    await page.getByRole('button', { name: '创建账号', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.locator('form').count(), 1);
    await page.getByLabel('用户名', { exact: true }).fill(report.username);
    await page.getByRole('button', { name: '创建账号', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: /already exists/ }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(logs, 'auth-register-mobile.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByLabel('用户名或邮箱', { exact: true }).fill(report.username);
    await page.getByLabel('密码', { exact: true }).fill('incorrect-password');
    await page.locator('form').getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: /incorrect/ }).waitFor();
    let releaseStale;
    let holdNextMe = true;
    await context.route('**/preprocessing/api/auth/me', async route => {
      if (!holdNextMe) return route.continue();
      holdNextMe = false;
      await new Promise(resolve => { releaseStale = resolve; });
      await route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ detail: 'Old session rejected' }) });
    });
    await page.getByLabel('密码', { exact: true }).fill('qa-test-only-password');
    const pendingMe = page.waitForRequest('**/preprocessing/api/auth/me');
    await page.locator('form').getByRole('button', { name: '登录', exact: true }).click();
    await pendingMe;
    await page.getByRole('navigation').waitFor();
    await page.getByRole('button', { name: '退出登录', exact: true }).click();
    await page.getByLabel('用户名或邮箱', { exact: true }).fill(report.username);
    await page.getByLabel('密码', { exact: true }).fill('qa-test-only-password');
    await page.locator('form').getByRole('button', { name: '登录', exact: true }).click();
    await page.getByRole('navigation').waitFor();
    const staleReply = page.waitForResponse(response => response.url().endsWith('/api/auth/me') && response.status() === 401);
    releaseStale();
    await staleReply;
    await page.waitForTimeout(100);
    assert.equal(await page.getByRole('navigation').count(), 1);
    await context.unroute('**/preprocessing/api/auth/me');
    await page.getByRole('link', { name: '切换账号', exact: true }).click();
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    await page.getByRole('button', { name: '继续使用当前账号', exact: true }).click();
    await page.getByRole('navigation').waitFor();
    await page.goto('http://127.0.0.1:5173/preprocessing/login');
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    await page.getByRole('button', { name: '继续使用当前账号', exact: true }).click();
    await page.getByRole('navigation').waitFor();
    await page.goto('http://127.0.0.1:5173/preprocessing/ai-analysis');
    await page.getByText(/Ollama · qwen3:4b-instruct-2507-q4_K_M/).waitFor();
    const config = await context.request.get('http://127.0.0.1:5000/api/ai-workflows/config', { headers: { Authorization: 'Bearer ' + auth.token } });
    const settings = await config.json();
    assert.equal(settings.provider, 'ollama');
    assert.equal(settings.configured, true);
    assert.equal('api_key' in settings, false);
    await page.getByRole('button', { name: '退出登录', exact: true }).click();
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, '/preprocessing/login');
    assert.equal(await page.evaluate(() => localStorage.getItem('ramancloud_auth_token')), null);
    await page.reload();
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    await page.evaluate(() => localStorage.setItem('ramancloud_auth_token', 'invalid-test-token'));
    await page.goto('http://127.0.0.1:5173/preprocessing/ai-analysis?task=test-target');
    await page.getByLabel('用户名或邮箱', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('ramancloud_auth_token')), null);
    await page.getByLabel('用户名或邮箱', { exact: true }).fill(report.username);
    await page.getByLabel('密码', { exact: true }).fill('qa-test-only-password');
    await page.locator('form').getByRole('button', { name: '登录', exact: true }).click();
    await page.waitForURL('**/preprocessing/ai-analysis?task=test-target');
    await page.goto('http://127.0.0.1:5173/preprocessing/nonexistent-page');
    await page.waitForURL(/\/preprocessing\/?$/);
    await page.getByRole('navigation').waitFor();
    assert.deepEqual(errors, []);
    report.passed = true;
    console.log('Auth checks passed: login/register/errors/remembered session/explicit login/logout/stale token/return route/mobile/Ollama metadata.');
  } finally {
    await fs.writeFile(path.join(logs, 'auth-ui-test-account.json'), JSON.stringify(report, null, 2));
    await browser.close();
    const cleanup = spawnSync(process.env.PYTHON_PATH || 'python', [path.resolve(__dirname, '../../backend/tests/cleanup_ui_test.py'), 'auth-ui-test-account.json'], { encoding: 'utf8' });
    console.log(cleanup.stdout);
    if (cleanup.status !== 0) throw new Error(cleanup.stderr || 'Auth QA cleanup failed');
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
