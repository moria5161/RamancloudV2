const PreferencesContext = createContext(null);

export function PreferencesProvider({ children }) {
  const { user, token } = useAuth();
  const [language, updateLanguage] = useState(() => readLanguage(window.localStorage));
  const [resolvedAccount, setResolvedAccount] = useState(null);
  const [languageError, setLanguageError] = useState(false);
  const guestChoice = useRef(null), revision = useRef(0), saves = useRef(Promise.resolve());
  const [theme, setTheme] = useState(() => localStorage.getItem('ramancloud_theme') || 'light');
  const endpoint = `${import.meta.env.BASE_URL.replace(/\/$/, '')}/api/account/preferences`;
  // Child renderers and non-React validation helpers use the same current locale.
  setActiveLanguage(language);

  const persist = useCallback((next, authToken) => {
    const current = ++revision.current;
    saves.current = saves.current.catch(() => {}).then(() => axios.put(endpoint, { language: next }, {
      headers: { Authorization: `Bearer ${authToken}` }, timeout: 10000,
    })).then(() => { if (current === revision.current) setLanguageError(false); })
      .catch(() => { if (current === revision.current) setLanguageError(true); });
  }, [endpoint]);

  const setLanguage = useCallback(next => {
    if (!validLanguage(next)) return;
    setActiveLanguage(next);
    updateLanguage(next);
    setLanguageError(false);
    if (user) {
      saveLanguage(window.localStorage, next, accountLanguageKey(user.id));
      persist(next, token);
    } else {
      guestChoice.current = next;
      saveLanguage(window.localStorage, next);
    }
  }, [user?.id, token, persist]);

  useEffect(() => {
    const current = ++revision.current, abort = new AbortController();
    setLanguageError(false);
    if (!user) {
      updateLanguage(readLanguage(window.localStorage));
      setResolvedAccount(null);
      return () => abort.abort();
    }
    const key = accountLanguageKey(user.id);
    let cached;
    try { cached = window.localStorage.getItem(key); } catch {}
    axios.get(endpoint, { headers: { Authorization: `Bearer ${token}` }, signal: abort.signal, timeout: 10000 })
      .then(({ data }) => {
        if (current !== revision.current) return;
        const next = validLanguage(data.language) ? data.language : guestChoice.current || (validLanguage(cached) ? cached : 'en');
        updateLanguage(next);
        saveLanguage(window.localStorage, next, key);
        setResolvedAccount(user.id);
        if (!validLanguage(data.language) && next !== 'en') persist(next, token);
        guestChoice.current = null;
      }).catch(error => {
        if (axios.isCancel(error) || current !== revision.current) return;
        updateLanguage(validLanguage(cached) ? cached : 'en');
        setResolvedAccount(user.id);
        setLanguageError(true);
      });
    return () => abort.abort();
  }, [user?.id, token, endpoint, persist]);

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }, [language]);

  useEffect(() => {
    localStorage.setItem('ramancloud_theme', theme);
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    languageError,
    retryLanguage: () => user && persist(language, token),
    localize: value => localize(value, language),
    locale: getLocale(),
    theme,
    setTheme,
    t: (key) => translations[language]?.[key] || translations.en[key] || key,
  }), [language, theme, setLanguage, languageError, user?.id, token, persist]);

  return <PreferencesContext.Provider value={value}>{user && resolvedAccount !== user.id
    ? <div className="app-liquid-bg h-screen flex items-center justify-center" role="status">Loading…</div>
    : children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  return useContext(PreferencesContext);
}
